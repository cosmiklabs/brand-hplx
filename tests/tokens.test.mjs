/** HPLX token cases, run against the vendored foundation's family API (ported from cosmiklabs/brand
 * 0.7.0 tests/tokens.test.mjs and check-browser.mjs, which covered HPLX while it lived there). */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {renderFamily, checkFamily, brandRelease} from '../vendor/brand/scripts/family.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const family = JSON.parse(read('tokens/family.json'));
const outputs = ['hplx.css', 'hplx.json', 'hplx.tokens.json', 'hplx_tokens.rs'];

/** A scratch copy of this family's source, so a mutation never touches the repository. */
function copy(t, mutate) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'brand-hplx-tokens-'));
  t.after(() => fs.rmSync(dir, {recursive: true, force: true}));
  fs.mkdirSync(path.join(dir, 'tokens'));
  const value = structuredClone(family);
  mutate?.(value);
  fs.writeFileSync(path.join(dir, 'tokens/family.json'), JSON.stringify(value, null, 2));
  return dir;
}

test('committed HPLX outputs are what the vendored release generates, and conform', () => {
  const result = checkFamily(root);
  assert.deepEqual(result.problems, []);
  assert.equal(result.id, 'hplx');
  assert.ok(result.checks >= 184, `${result.checks} contrast pairs`);
});

test('generated headers name the vendored brand release and only relative paths', () => {
  const {name, version} = brandRelease();
  const provenance = `Generated by ${name} ${version} scripts/family.mjs from tokens/family.json over kits/cosmik/tokens/source.json`;
  for (const file of outputs) {
    const text = read(`tokens/${file}`);
    if (file !== 'hplx.json') assert.ok(text.includes(provenance), file);
    for (const absolute of [root, os.homedir()]) assert.equal(text.includes(absolute), false, `${file} leaks ${absolute}`);
  }
});

test('the generator rejects a negative shadow blur', t => {
  const dir = copy(t, s => { s.elevation['1'].blur = '-2px'; });
  assert.throws(() => renderFamily(dir), /finite number >= 0/);
});

test('valid signed shadow offsets and spread survive the native output', t => {
  const dir = copy(t, s => { s.elevation['1'].offsetX = '-2px'; s.elevation['1'].spread = '-1px'; });
  const json = JSON.parse(renderFamily(dir).files.find(([name]) => name === 'hplx.json')[1]);
  assert.equal(json.native.elevation.dark['1'].offsetXPx, -2);
  assert.equal(json.native.elevation.dark['1'].spreadPx, -1);
});

test('Spectral sets the HPLX heading roles only; utility type stays Inter', () => {
  const json = JSON.parse(read('tokens/hplx.json'));
  for (const role of ['display', 'display-small', 'section', 'card']) assert.match(json.type[role].fontFamily, /Spectral/, role);
  for (const role of ['body', 'control', 'ui', 'ui-small', 'label']) assert.doesNotMatch(json.type[role].fontFamily, /Spectral/, role);
  for (const font of family.fonts) {
    for (const file of [...Object.values(font.files), font.license_file]) assert.ok(fs.existsSync(path.join(root, file)), file);
  }
});

test('the HPLX scope sets its own surface in both modes and an elevation shadow', () => {
  const css = read('tokens/hplx.css');
  const json = JSON.parse(read('tokens/hplx.json'));
  assert.match(css, /^\[data-family="hplx"\] \{/m);
  assert.notEqual(json.semantic.dark.bg, json.semantic.light.bg);
  assert.match(css, /--c-elevation-2-shadow: /);
});
